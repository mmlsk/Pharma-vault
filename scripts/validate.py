#!/usr/bin/env python3
"""Quality gate for the vault and the catalogue.

Checks
  1. Every note in vault/04 Compound Notes validates against the v2 JSON Schema.
  2. The example frontmatter in the compound template validates.
  3. compound-id values are unique across the vault.
  4. Every [[wikilink]] in the vault resolves to an existing note/file.
  5. Alias collisions from the catalogue build are reported (warning, not failure).

Writes a Markdown report (default: vault/90 Templates/Schema Validation Report.md)
and exits with status 1 if any hard check fails.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import Counter
from datetime import date

import yaml
from jsonschema import Draft202012Validator, FormatChecker

from pv_common import COMPOUND_NOTES, PROCESSED, SCHEMA, VAULT

FRONTMATTER = re.compile(r"^---\n(.*?)\n---\n", re.S)
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
TEMPLATE = VAULT / "90 Templates/Compound Note Template.md"
TEMPLATE_EXAMPLE = VAULT / "90 Templates/Compound Note Example.md"


def load_fm(path):
    m = FRONTMATTER.match(path.read_text(encoding="utf-8"))
    if not m:
        return None
    # Obsidian writes dates unquoted; keep them as strings for JSON Schema.
    return json.loads(json.dumps(yaml.safe_load(m.group(1)) or {}, default=str))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--report", default=str(VAULT / "90 Templates/Schema Validation Report.md"))
    ap.add_argument("--no-report", action="store_true")
    args = ap.parse_args()

    validator = Draft202012Validator(json.loads(SCHEMA.read_text()), format_checker=FormatChecker())
    errors: list[str] = []

    notes = sorted(COMPOUND_NOTES.rglob("*.md"))
    ids = Counter()
    statuses = Counter()
    for p in notes + [TEMPLATE_EXAMPLE]:
        fm = load_fm(p)
        rel = p.relative_to(VAULT)
        if fm is None:
            errors.append(f"`{rel}`: missing frontmatter")
            continue
        for e in validator.iter_errors(fm):
            loc = "/".join(map(str, e.absolute_path)) or "(root)"
            errors.append(f"`{rel}` → `{loc}`: {e.message}")
        if p != TEMPLATE_EXAMPLE:
            ids[fm.get("compound-id")] += 1
            statuses[fm.get("review-status")] += 1
    dup_ids = [k for k, v in ids.items() if v > 1]
    errors += [f"duplicate compound-id `{d}`" for d in dup_ids]

    # Wikilinks: resolve by note basename (Obsidian default "shortest path").
    names = {p.stem.lower() for p in VAULT.rglob("*.md")} | {p.name.lower() for p in VAULT.rglob("*.*")}
    names.add("schema validation report")  # written by this script
    broken = Counter()
    for p in VAULT.rglob("*.md"):
        if p == TEMPLATE:
            continue
        text = re.sub(r"```.*?```", "", p.read_text(encoding="utf-8"), flags=re.S)
        for target in WIKILINK.findall(text):
            t = target.strip().split("/")[-1].lower()
            if t not in names and f"{t}.md" not in names:
                broken[target.strip()] += 1
    errors += [f"broken wikilink `[[{t}]]` ×{n}" for t, n in sorted(broken.items())]

    collisions = []
    cpath = PROCESSED / "alias-collisions.csv"
    if cpath.exists():
        with open(cpath, encoding="utf-8") as fh:
            collisions = list(csv.DictReader(fh))

    ok = not errors
    lines = [
        "---", "type: report", f"generated: {date.today().isoformat()}", "tags: [report, validation]", "---", "",
        "# Schema Validation Report", "",
        "> Generated by `scripts/validate.py` - do not edit by hand.", "",
        f"- **Schema:** `schemas/{SCHEMA.name}` (JSON Schema draft 2020-12)",
        f"- **Compound notes checked:** {len(notes)}",
        f"- **Review status:** " + ", ".join(f"{k}: {v}" for k, v in sorted(statuses.items(), key=str)),
        f"- **Template example valid:** {'yes' if not any(str(TEMPLATE_EXAMPLE.name) in e for e in errors) else 'no'}",
        f"- **Result:** {'✅ PASS' if ok else '❌ FAIL'} ({len(errors)} error(s))", "",
        "## Errors", "",
        *([f"- {e}" for e in errors[:200]] or ["None."]), "",
        "## Alias collisions (review queue)", "",
        "Names that normalise to the same key but belong to different compound ids. Most are duplicates "
        "to be merged under one canonical id; some are genuine ambiguities (e.g. *ALA*).", "",
        "| Normalised name | Compound ids | Labels |", "|---|---|---|",
        *[f"| `{c['normalized_name']}` | {c['compound_ids']} | {c['labels']} |" for c in collisions], "",
    ]
    if not args.no_report:
        with open(args.report, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
    print(f"notes={len(notes)} errors={len(errors)} alias_collisions={len(collisions)} result={'PASS' if ok else 'FAIL'}")
    for e in errors[:20]:
        print("  -", e)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
